export const handlePermissions = (e: any, setvalue: any, isURLesterno?: boolean) => {
  const currentElchecked = e.target.checked;
  const El = e.target;
  const elId = El.getAttribute('id');
  const isParent = elId?.includes('-') ? false : true;
  isURLesterno = isURLesterno != undefined ? isURLesterno : false;//handling undefined 
  let parentName: string = "";
  let parentValue: boolean = false;
  let fieldName: string = "";
  let fieldValue: string[] = [];
  if (isParent) {
    const parentEl = El;
    const childEls = document.getElementsByClassName(`${elId}-child`);
    parentName = parentEl.getAttribute("name");
    if (currentElchecked) {
      parentEl.checked = true;
      parentValue = true;
      Array.from(childEls)?.map((el: any) => {
        el.checked = true;
        fieldName = el.getAttribute('name');
        fieldValue.push(el.value);
        isURLesterno && setvalue(fieldName, true);
      })
    } else {
      parentEl.checked = false;
      Array.from(childEls)?.map((el: any) => {
        el.checked = false;
        fieldName = el.getAttribute('name');
        fieldValue = [];
        isURLesterno && setvalue(fieldName, false);
      })
    }
    !isURLesterno && setvalue(parentName, parentValue)
    !isURLesterno && setvalue(fieldName, fieldValue);
  } else {
    const elClasses = Array.from(El.classList);
    const childClass: any = elClasses.filter((cls: any) => cls.includes('child'))[0];//0 is for taking the first value of array and assign it to string
    const parentId = childClass.split('-')[0];
    const parentEl: any = document.getElementById(parentId);
    const childEls = document.getElementsByClassName(childClass);
    parentName = parentEl.getAttribute("name");
    fieldName = El.getAttribute("name");
    const checkedchildEls = Array.from(childEls).filter((el: any) => el.checked == true)
      ?.map((el: any) => fieldValue.push(el.value));
    if (checkedchildEls.length == 0) {
      parentEl.checked = false;
      fieldValue = [];
    }
    else {
      parentEl.checked = true;
      parentValue = true;
    }
    setvalue(parentName, parentValue);
    if (!isURLesterno)
      setvalue(fieldName, fieldValue);
    else {
      setvalue(fieldName, El.checked);
    }
  }

}

